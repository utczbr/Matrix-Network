#!/usr/bin/env python3
"""Back-of-envelope capacity model for the Matrix Factory Twin.

Purpose: choose the P3 sweep levels (fleet size N, PHY rate, telemetry rate) so
that both domains are driven from lightly loaded to saturated, instead of
guessing. This is an analytic ESTIMATE, not a simulation result:
  * 802.11 timing is approximate 802.11g ERP-OFDM (values below); replace the
    exchange times with INET's measured frameSequenceDuration from a single-AMR,
    no-load run as soon as you have one.
  * Utilization ignores collisions and retries, so real saturation starts
    EARLIER than the numbers here (treat them as a lower bound on load).

Usage:  python3 analysis/capacity.py            # prints Markdown to stdout
        python3 analysis/capacity.py --out docs/capacity.md
Keep the traffic constants in sync with docs/parameters.md (section 4).
"""
import argparse
import math

# ---- 802.11g ERP-OFDM timing (approximate) ---------------------------------
SLOT = 9e-6            # short slot (ERP-OFDM only network)
SIFS = 10e-6
DIFS = SIFS + 2 * SLOT
PREAMBLE = 20e-6       # 16 us preamble + 4 us SIGNAL
SYMBOL = 4e-6
SIGEXT = 6e-6          # signal extension in the 2.4 GHz band
CWMIN = 15             # ERP-OFDM; verify against INET's mode set
MANDATORY = (6e6, 12e6, 24e6)    # control responses use a mandatory rate
MAC_OVERHEAD_B = 8 + 20 + 8 + 24 + 4   # UDP + IP + LLC/SNAP + MAC header + FCS
ACK_B = 14

# ---- traffic (keep in sync with docs/parameters.md section 4) ---------------
STATE_B, STATE_HZ = 1000, 10.0      # AMR -> FMS (uplink)
ORDER_B, ORDER_HZ = 600, 5.0        # FMS -> AMR (downlink), mean of exponential(200 ms)
TEL_B = 1400                        # station -> FMS (wired only)
N_STATIONS = 4
TEL_INTERVALS = (2e-3, 600e-6, 300e-6)

# ---- wired -------------------------------------------------------------------
WIRE_RATE = 100e6
WIRE_OVERHEAD_B = 58 + 12           # headers+preamble (58 B) + inter-frame gap (12 B)
TEL_WINDOW = 500e-6                 # TAS telemetry window
GATE_CYCLE = 1e-3

PHY_RATES = (54e6, 24e6, 12e6, 6e6)
FLEET = (5, 10, 20, 40, 80, 120, 200)
TARGETS = (0.10, 0.30, 0.60, 0.90)


def ack_rate(rate):
    return max(m for m in MANDATORY if m <= rate)


def frame_time(app_bytes, rate):
    length = app_bytes + MAC_OVERHEAD_B
    nsym = math.ceil((16 + 8 * length + 6) / (rate * SYMBOL))
    return PREAMBLE + nsym * SYMBOL + SIGEXT


def ack_time(rate):
    nsym = math.ceil((16 + 8 * ACK_B + 6) / (ack_rate(rate) * SYMBOL))
    return PREAMBLE + nsym * SYMBOL + SIGEXT


def exchange(app_bytes, rate, backoff_slots):
    """One successful DATA/ACK exchange including DIFS and backoff."""
    return DIFS + backoff_slots * SLOT + frame_time(app_bytes, rate) + SIFS + ack_time(rate)


def per_amr_load(rate, backoff_slots):
    """Airtime (s per s) one AMR adds: its state uplink + its order downlink."""
    return (STATE_HZ * exchange(STATE_B, rate, backoff_slots)
            + ORDER_HZ * exchange(ORDER_B, rate, backoff_slots))


def wire_frame_time(payload):
    return (payload + WIRE_OVERHEAD_B) * 8 / WIRE_RATE


def mbps(x):
    return x / 1e6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="write Markdown here instead of stdout")
    args = ap.parse_args()
    out = []
    w = out.append

    w("# Capacity analysis (generated by analysis/capacity.py)\n")
    w("Analytic estimate, not a simulation result. 802.11g ERP-OFDM timing is approximate and "
      "utilization ignores collisions and retries, so real saturation starts earlier than shown. "
      "Replace the exchange times with INET's measured values from a single-AMR, no-load run.\n")
    w(f"Assumed traffic: state {STATE_B} B at {STATE_HZ:g} Hz per AMR (uplink); orders {ORDER_B} B at "
      f"{ORDER_HZ:g} Hz per AMR (downlink, shares the same medium); {N_STATIONS} stations send "
      f"{TEL_B} B telemetry over the wire only.\n")

    # 1. exchange times
    w("## 1. Airtime per successful exchange\n")
    w("| PHY rate | ACK rate | State exchange, CSMA (us) | Order exchange, CSMA (us) | "
      "State exchange, scheduled cw=0 (us) | Max state packets/s (CSMA) |")
    w("|---|---|---|---|---|---|")
    for r in PHY_RATES:
        s = exchange(STATE_B, r, CWMIN / 2)
        o = exchange(ORDER_B, r, CWMIN / 2)
        ss = exchange(STATE_B, r, 0)
        w(f"| {mbps(r):g} Mbps | {mbps(ack_rate(r)):g} Mbps | {s*1e6:.0f} | {o*1e6:.0f} | "
          f"{ss*1e6:.0f} | {1/s:.0f} |")
    w("\nCSMA exchange includes DIFS, the mean backoff (CWmin/2 slots), preamble, data, SIFS and ACK. "
      "The scheduled column has zero backoff. Its value is the minimum slot length for the largest "
      "wireless frame (state); add a safety margin when you choose `slotDuration`.\n")

    # 2. utilization vs N
    w("## 2. Wireless utilization (%) versus fleet size and PHY rate (CSMA, no collisions)\n")
    w("| N (AMRs) | " + " | ".join(f"{mbps(r):g} Mbps" for r in PHY_RATES) + " |")
    w("|---|" + "---|" * len(PHY_RATES))
    for n in FLEET:
        cells = []
        for r in PHY_RATES:
            u = 100 * n * per_amr_load(r, CWMIN / 2)
            cells.append(f"{u:.0f}" + (" (>100)" if u > 100 else ""))
        w(f"| {n} | " + " | ".join(cells) + " |")
    w("")

    # 3. N at target utilization
    w("## 3. Fleet size that reaches a target utilization\n")
    w("| Target | " + " | ".join(f"{mbps(r):g} Mbps" for r in PHY_RATES) + " |")
    w("|---|" + "---|" * len(PHY_RATES))
    for t in TARGETS:
        cells = [f"{t / per_amr_load(r, CWMIN / 2):.0f}" for r in PHY_RATES]
        w(f"| {int(t*100)}% | " + " | ".join(cells) + " |")
    w("\nReading: with the placeholder rates, a 54 Mbps cell stays lightly loaded for the whole "
      "5-40 AMR range, so 802.11 contention is unlikely to dominate. To observe it, lower the PHY "
      "rate, extend the fleet range, or raise per-AMR traffic (real VDA 5050 state sizes and rates "
      "are the open question, decisions.md Q6).\n")

    # 4. wired
    w("## 4. Wired offered load on the switch-to-FMS port (100 Mbps)\n")
    w("| N (AMRs) | State (Mbps) | " + " | ".join(
        f"+ telemetry {t*1e6:.0f} us ({N_STATIONS*TEL_B*8/t/1e6:.1f} Mbps)" for t in TEL_INTERVALS) + " |")
    w("|---|---|" + "---|" * len(TEL_INTERVALS))
    for n in FLEET:
        st = n * STATE_HZ * (STATE_B + WIRE_OVERHEAD_B) * 8 / 1e6
        cells = []
        for t in TEL_INTERVALS:
            tel = N_STATIONS * (TEL_B + WIRE_OVERHEAD_B) * 8 / t / 1e6
            cells.append(f"{st + tel:.1f}")
        w(f"| {n} | {st:.1f} | " + " | ".join(cells) + " |")
    ft = wire_frame_time(TEL_B)
    frames = int(TEL_WINDOW // ft)
    cap = frames * TEL_B * 8 / GATE_CYCLE / 1e6
    w(f"\nValues include headers and the 12 B gap. Under TAS, telemetry fits {frames} frames per "
      f"{TEL_WINDOW*1e6:.0f} us window, a payload ceiling of about {cap:.1f} Mbps, so TAS cells throttle "
      "telemetry by design while FIFO carries it up to link saturation.\n")
    o_load = [(n, n * ORDER_HZ * (ORDER_B + WIRE_OVERHEAD_B) * 8 / 1e6) for n in FLEET]
    w("Orders on the switch-to-AP port: " + ", ".join(f"N={n}: {l:.2f} Mbps" for n, l in o_load)
      + ". With the placeholder GCL the orders window carries at most "
      f"{int(100e-6 // wire_frame_time(ORDER_B))} frame per 1 ms cycle "
      f"({1/GATE_CYCLE:.0f} orders/s), so check it against N x {ORDER_HZ:g} orders/s.\n")

    text = "\n".join(out)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    else:
        print(text)


if __name__ == "__main__":
    main()
